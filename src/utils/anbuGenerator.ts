// ── 滑块标签 ────────────────────────────────────────────────────────────────

export function getStyleLabel(w: number): string {
  if (w <= 0.15) return '压抑如深夜';
  if (w <= 0.30) return '克制·忧郁';
  if (w <= 0.45) return '平静·留白';
  if (w <= 0.55) return '冷幽默';
  if (w <= 0.70) return '吐槽上线';
  if (w <= 0.85) return '荒诞已启动';
  return '卡卡西很困扰';
}

// ── 主生成函数 ────────────────────────────────────────────────────────────────

export function generateAnbuEntry(itemLabel: string, styleWeight: number): string {
  const pool = POOLS.find((p) => p.keywords.test(itemLabel)) ?? FALLBACK;

  // 中间地带（0.45–0.55）有概率抽 mid 句
  const inMidZone = styleWeight > 0.45 && styleWeight < 0.55;
  if (inMidZone && pool.mid.length > 0 && Math.random() < 0.4) {
    return pick(pool.mid);
  }

  if (styleWeight < 0.5) {
    // 偏严肃：主要抽 serious，小概率混入 mid
    const candidates = styleWeight < 0.25
      ? pool.serious
      : [...pool.serious, ...pool.serious, ...(pool.mid.length ? pool.mid : [])];
    return pick(candidates);
  } else {
    // 偏荒诞：主要抽 absurd，小概率混入 mid
    const candidates = styleWeight > 0.75
      ? pool.absurd
      : [...pool.absurd, ...pool.absurd, ...(pool.mid.length ? pool.mid : [])];
    return pick(candidates);
  }
}
